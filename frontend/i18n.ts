const MESSAGES: Record<ImageGenLang, Messages> = { en, pt, es, zh }

export type ImageGenTranslator = (key: string, args?: Record<string, string>) => string

/** Translate a key for the active language. */
export function translate(lang: ImageGenLang, key: string, args?: Record<string, string>): string {
  const bundle = MESSAGES[lang] || en
  let msg = bundle[key] ?? en[key] ?? key
  if (args) {
    for (const [k, v] of Object.entries(args)) {
      msg = msg.replace(new RegExp(`\\{${k}\\}`, 'g'), v)
    }
  }
  return msg
}

// The REST layer localizes backend error codes, and it is not a React tree,
// so it cannot read the context. The provider mirrors its language here.
let activeLang: ImageGenLang = DEFAULT_LANG

/**
 * Translate for the active language from outside React.
 *
 * This is the exported seam over the module-private `activeLang`, not a
 * rename of `translate`: `api.rest` localizes backend error codes and has no
 * context to read. Inlining it is not possible without exporting the mutable
 * language itself.
 */
export function translateActive(key: string, args?: Record<string, string>): string {
  return translate(activeLang, key, args)
}

/** Build a bound translator for a language. */
export function useImageGenI18n(lang: ImageGenLang): (key: string, args?: Record<string, string>) => string {
  return useMemo(() => (key: string, args?: Record<string, string>) => translate(lang, key, args), [lang])
}

const ImageGenI18nContext = createContext<ImageGenTranslator | null>(null)

export function ImageGenI18nProvider({ lang, children }: { lang: ImageGenLang; children: ReactNode }) {
  const translator = useImageGenI18n(lang)
  activeLang = lang
  return createElement(ImageGenI18nContext.Provider, { value: translator }, children)
}

/** The language on screen, for tables that live outside the message bundles. */
export function activeLangOf(): ImageGenLang {
  return activeLang
}

export function useImageGenT(): ImageGenTranslator {
  const translator = useContext(ImageGenI18nContext)
  return translator || translateActive
}
