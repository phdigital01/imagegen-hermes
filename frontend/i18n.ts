/**
 * ImageGen — plugin-scoped i18n.
 *
 * The plugin ships pt, en, es and zh. By default it follows the Hermes app
 * language (`useI18n().locale`) and falls back to English; a persisted
 * selector lets the user pin one of the four instead.
 */

import { createContext, createElement, useContext, useMemo, type ReactNode } from 'react'

export type ImageGenLang = 'pt' | 'en' | 'es' | 'zh'

export const IMAGEGEN_LANGS: ImageGenLang[] = ['pt', 'en', 'es', 'zh']
const DEFAULT_LANG: ImageGenLang = 'en'

/** The persisted preference: follow the app (`auto`) or pin a language. */
export type ImageGenLangChoice = 'auto' | ImageGenLang

/** Map a Hermes app locale (`pt-BR`, `es`, `zh-hant`, …) to a plugin language. */
function langFromLocale(locale: string | undefined): ImageGenLang {
  const base = (locale || '').toLowerCase().split(/[-_]/)[0]
  return (IMAGEGEN_LANGS as string[]).includes(base) ? (base as ImageGenLang) : DEFAULT_LANG
}

export function resolveLang(choice: ImageGenLangChoice, locale: string | undefined): ImageGenLang {
  return choice === 'auto' || !IMAGEGEN_LANGS.includes(choice) ? langFromLocale(locale) : choice
}

